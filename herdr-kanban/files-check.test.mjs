// HK41: the Builder checks the plan's ## Files before its first edit (hkb files), and a missing file
// hands back through the existing [planning] issue with no edit made.
import { test } from 'node:test'
import assert from 'node:assert/strict'
import { mkdtempSync, mkdirSync, writeFileSync, readFileSync, rmSync } from 'node:fs'
import { join, resolve } from 'node:path'
import { tmpdir } from 'node:os'
import { spawnSync } from 'node:child_process'
import { missingFromFiles, readOnlyFromFiles, validatePlan } from './lib/cards.mjs'
import { workerPrompt } from './lib/prompt.mjs'

const CARD = `# T-1 — card
**Workflow:** card-owned
**Workflow version:** 2
## Files
- \`herdr-kanban/a.mjs\` lines 1-5, \`fn\` — change it
- \`herdr-kanban/new.test.mjs\` (new) — the test
- \`herdr-kanban/gen/**\` — generated by the build
- \`herdr-kanban/ro.mjs\` — unchanged, read only
## Acceptance criteria
- AC1: first
## Evidence
<!-- none -->
`

test('AC2: missingFromFiles reports exactly the uncovered paths, [] when none', () => {
  const needed = ['herdr-kanban/a.mjs', './herdr-kanban/a.mjs', 'herdr-kanban\\A.mjs', 'herdr-kanban/new.test.mjs', 'herdr-kanban/gen/x/y.js', 'herdr-kanban/ro.mjs', 'public/app.js', 'public/app.js', 'herdr-kanban/b.mjs']
  assert.deepEqual(missingFromFiles(CARD, needed), ['public/app.js', 'herdr-kanban/b.mjs'])
  assert.deepEqual(readOnlyFromFiles(CARD, needed), ['herdr-kanban/ro.mjs'])
  assert.deepEqual(missingFromFiles(CARD, needed.slice(0, 5)), [])
})

const hkb = (tasks, ...args) => spawnSync(process.execPath, [resolve('hkb.mjs'), '--tasks', tasks, ...args], { encoding: 'utf8', windowsHide: true })
function board(t, lane = 'working') {
  const root = mkdtempSync(join(tmpdir(), 'files-check-')), tasks = join(root, 'TASKS')
  t.after(() => rmSync(root, { recursive: true, force: true }))
  mkdirSync(join(tasks, lane), { recursive: true })
  const path = join(tasks, lane, 'T-1.md')
  writeFileSync(path, CARD)
  return { tasks, path }
}

test('AC2/AC3: files verb passes when covered, names exactly the missing files with [planning], writes nothing', t => {
  const { tasks, path } = board(t)
  const ok = hkb(tasks, 'files', 'T-1', 'herdr-kanban/a.mjs', 'herdr-kanban/gen/z.js')
  assert.equal(ok.status, 0, ok.stdout + ok.stderr)
  assert.match(ok.stdout, /FILES OK T-1: all 2 paths/)
  const bad = hkb(tasks, 'files', 'T-1', 'herdr-kanban/a.mjs', 'public/app.js', 'herdr-kanban/ro.mjs')
  assert.equal(bad.status, 1)
  assert.match(bad.stdout, /FILES MISSING T-1: public\/app\.js\n/)
  assert.match(bad.stdout, /\[planning\] ## Files misses: public\/app\.js/)
  assert.doesNotMatch(bad.stdout, /ro\.mjs/)
  assert.doesNotMatch(bad.stdout, /herdr-kanban\/a\.mjs/)
  assert.equal(readFileSync(path, 'utf8'), CARD)
  for (const args of [[], ['/abs/x.js'], ['C:/x.js'], ['../x.js']]) assert.equal(hkb(tasks, 'files', 'T-1', ...args).status, 1, args.join(' '))
})

// A path the plan lists as read-only (not a miss) is reported as read-only, exit 0, and is not added or written.
test('files: a path listed as read-only is FILES OK (read-only, do not edit) and writes nothing', t => {
  const { tasks, path } = board(t)
  const ro = hkb(tasks, 'files', 'T-1', 'herdr-kanban/ro.mjs')
  assert.equal(ro.status, 0, ro.stdout + ro.stderr)
  assert.match(ro.stdout, /FILES OK \(read-only, do not edit\) T-1: herdr-kanban\/ro\.mjs/)
  const mixed = hkb(tasks, 'files', 'T-1', 'herdr-kanban/a.mjs', 'herdr-kanban/ro.mjs')
  assert.equal(mixed.status, 0, mixed.stdout + mixed.stderr)
  assert.match(mixed.stdout, /FILES OK T-1: all 2 paths are in ## Files; edit now \(read-only, do not edit: herdr-kanban\/ro\.mjs\)/)
  assert.equal(readFileSync(path, 'utf8'), CARD)
})

// The other spellings a plan uses for read-only ("-- read only", "— read only") are read-only too, so a Builder is never told to edit them.
test('files: "-- read only" and "— read only" bullets are read-only, not edit paths', () => {
  const text = CARD.replace('- `herdr-kanban/ro.mjs` — unchanged, read only', '- `herdr-kanban/ro.mjs` -- read only\n- `herdr-kanban/ro2.mjs` — read only')
  assert.deepEqual(readOnlyFromFiles(text, ['herdr-kanban/ro.mjs', 'herdr-kanban/ro2.mjs', 'herdr-kanban/a.mjs']), ['herdr-kanban/ro.mjs', 'herdr-kanban/ro2.mjs'])
  assert.deepEqual(missingFromFiles(text, ['herdr-kanban/ro.mjs', 'herdr-kanban/ro2.mjs']), [])
})

// IA305 (16 Oct 2026): the marker came before the path ("- Read-only, no change: `e2e/demo-data.ts` lines 31-56"), so both the
// read-only file and a path with parentheses were reported as misses. Both are read-only now, and the files verb says so with exit 0.
test('files: a read-only marker before the path is read-only, parentheses in the path included', t => {
  const { tasks, path } = board(t)
  const text = CARD.replace('- `herdr-kanban/ro.mjs` — unchanged, read only', '- Read-only, no change: `herdr-kanban/ro.mjs` lines 1-3, `fn`\n- Read-only, no change: `herdr-kanban/src/app/(tabs)/plotter.tsx` (renders the picker at line 61)')
  writeFileSync(path, text)
  const paths = ['herdr-kanban/ro.mjs', 'herdr-kanban/src/app/(tabs)/plotter.tsx']
  assert.deepEqual(readOnlyFromFiles(text, paths), paths)
  assert.deepEqual(missingFromFiles(text, paths), [])
  const r = hkb(tasks, 'files', 'T-1', ...paths)
  assert.equal(r.status, 0, r.stdout + r.stderr)
  assert.match(r.stdout, /FILES OK \(read-only, do not edit\) T-1: herdr-kanban\/ro\.mjs, herdr-kanban\/src\/app\/\(tabs\)\/plotter\.tsx/)
  assert.doesNotMatch(r.stdout, /MISSING/)
  assert.equal(readFileSync(path, 'utf8'), text)
})

test('files verb refuses a card outside working', t => {
  const { tasks } = board(t, 'queue')
  const r = hkb(tasks, 'files', 'T-1', 'herdr-kanban/a.mjs')
  assert.equal(r.status, 1)
  assert.match(r.stderr + r.stdout, /in queue/)
})

test('AC1/AC3: the Builder brief runs the Files check, with the [planning] hand-back, before any edit step', () => {
  const w = workerPrompt({ card: { id: 'IA999', category: 'ui', column: 'approved', path: 'C:/fake/card.md', trivial: false, title: 'x' }, projectPath: 'C:/fake/project', boardRoot: 'C:/Users/PFrew/Projects/herdr-kanban', tasksDir: null, engine: 'claude' })
  const at = w.search(/ files IA999 </)
  assert.ok(at > 0, 'brief lacks the files command')
  assert.match(w, /reports a file missing, rerun with --add "<why>" \(max two tracked files\); if still missing, hand back at once with the issue command below, category \[planning\], naming each missing file, no edit/)
  assert.match(w, /operator clarification, never self-approved widening/)
  assert.match(w, /A read-only listed path is never edited/)
  for (const later of ['Follow known functions', 'git -C', ' result IA999 ']) {
    const i = w.indexOf(later)
    assert.ok(i > at, `"${later}" (${i}) must come after the files command (${at})`)
  }
})

// Injectbuddy I1317-I1320 and I1324 (15 Oct 2026): one ## Files bullet named many paths. The board read only the first,
// so the Builder's files check kicked each card back. A bullet with more than one path is refused at the plan check.
const planWith = (files) => `**Difficulty:** medium
**Workflow version:** 2
**Plan readiness:** build-ready
**Workspace:** .
## Approved brief
Deliver the agreed outcome.
## Files
${files}
## Acceptance criteria
- AC1: first
`
const onlyPathMessage = (text) => { try { validatePlan(text) } catch (err) { return err.message } return '' }

test('HK41: a ## Files bullet naming several paths is refused, and one path per bullet is accepted', () => {
  const multi = planWith('- `public/legacy/a/index.html`, `public/legacy/b/index.html` — remove the preload')
  assert.match(onlyPathMessage(multi), /also names public\/legacy\/b\/index\.html; only the first path on a bullet is read/)
  const oneEach = planWith('- `public/legacy/a/index.html` — remove the preload\n- `public/legacy/b/index.html` — remove the preload')
  assert.doesNotMatch(onlyPathMessage(oneEach), /only the first path on a bullet/)
  const prose = planWith('- `herdr-kanban/a.mjs` lines 1-5, `fn` — change it\n- `herdr-kanban/ro.mjs` — unchanged, read only, see `herdr-kanban/other.mjs`')
  assert.doesNotMatch(onlyPathMessage(prose), /only the first path on a bullet/)
  const generated = planWith('- `public/legacy/*/index.html` — generated by `scripts/gen.mjs`\n- `scripts/gen.mjs` — the generator')
  assert.doesNotMatch(onlyPathMessage(generated), /only the first path on a bullet/)
})
