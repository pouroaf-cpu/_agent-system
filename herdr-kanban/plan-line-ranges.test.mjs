// HK27: a build-ready plan handed off by a Planner names each place to change as
// `path` lines START-END, `name`, and the name must occur in that range.
import assert from 'node:assert/strict'
import { test } from 'node:test'
import { mkdtempSync, mkdirSync, writeFileSync, existsSync, readFileSync, rmSync } from 'node:fs'
import { join, resolve } from 'node:path'
import { tmpdir } from 'node:os'
import { spawnSync } from 'node:child_process'
import { validatePlan } from './lib/cards.mjs'
import { workerPrompt } from './lib/prompt.mjs'

const root = mkdtempSync(join(tmpdir(), 'plan-ranges-'))
mkdirSync(join(root, 'src'))
writeFileSync(join(root, 'src', 'app.mjs'), Array.from({ length: 30 }, (_, i) => i === 9 ? 'function handleKeyDown(event) {}' : `// line ${i + 1}`).join('\n') + '\n')
writeFileSync(join(root, 'src', 'multi.mjs'), Array.from({ length: 14 }, (_, i) => i === 2 || i === 11 ? 'function handleKeyDown(event) {}' : `// line ${i + 1}`).join('\n') + '\n')
mkdirSync(join(root, 'proj', 'lib'), { recursive: true })
writeFileSync(join(root, 'proj', 'lib', 'cards.mjs'), 'export {}\n')
for (const args of [['init'], ['add', '.'], ['-c', 'user.name=t', '-c', 'user.email=t@t', 'commit', '-m', 'x']]) spawnSync('git', ['-C', root, ...args], { windowsHide: true })

const plan = ({ header = '', files = '- `src/app.mjs` lines 5-15, `handleKeyDown()` — handler\n- `test/app.test.mjs` (new) — focused check', changes = '- `src/app.mjs` lines 5-15, `handleKeyDown()`: guard Enter.' } = {}) => `# HK1 — ranges
${header}**Difficulty:** medium
**Workflow version:** 2
**Plan readiness:** build-ready
**Workspace:** .
## Approved brief
Deliver it.
## Files
${files}
## Implementation plan
Outcome: guard Enter.
Unchanged constraints: no API changes.
Cause: handleKeyDown drops Enter.
Evidence: src/app.mjs line 10.
Inspected current state: clean.
Changes: one edit, pointed below.
${changes}
Scope: only listed files.
**Callers checked:** none
## Acceptance criteria
- AC1: Enter works.
## Prerequisites
Node runtime.
`
const options = { requireReadiness: true, workspace: root }
test.after(() => rmSync(root, { recursive: true, force: true }))

test('AC1: a Files entry or Changes entry without a line range is refused and named', () => {
  assert.throws(() => validatePlan(plan({ files: '- `src/app.mjs` — handler' }), options), /## Files entry src\/app\.mjs has no line range/)
  assert.throws(() => validatePlan(plan({ changes: '- `src/app.mjs`: guard Enter.' }), options), /Changes entry "- `src\/app\.mjs`: guard Enter\." names src\/app\.mjs with no line range/)
  assert.throws(() => validatePlan(plan({ changes: '- guard Enter in `handleKeyDown()`.' }), options), /names handleKeyDown\(\) with no line range/)
  // Exempt: new files, reference-only bullets, generated globs; plans not handed off by a Planner.
  assert.doesNotThrow(() => validatePlan(plan({ files: '- `src/app.mjs` lines 5-15, `handleKeyDown()` — h\n- `src/a.test.mjs` (new) — t\n- `src/app.mjs` — unchanged\n- `src/*.mjs` — generated by `src/app.mjs`' }), { requireReadiness: true }))
  assert.doesNotThrow(() => validatePlan(plan({ files: '- `src/app.mjs` — handler' })))
})

test('AC2: a range that lacks the name is refused and named', () => {
  assert.throws(() => validatePlan(plan({ files: '- `src/app.mjs` lines 20-30, `handleKeyDown()` — h' }), options), /src\/app\.mjs lines 20-30: `handleKeyDown\(\)` does not occur/)
  assert.throws(() => validatePlan(plan({ files: '- `src/app.mjs` lines 25-99, `handleKeyDown()` — h' }), options), /lines 25-99.*file has 30 lines/)
  assert.throws(() => validatePlan(plan({ changes: '- `src/app.mjs` lines 20-30, `handleKeyDown()`: guard.' }), options), /## Implementation plan src\/app\.mjs lines 20-30/)
  // A blocked card is planned against files its blocker still changes: format only.
  assert.doesNotThrow(() => validatePlan(plan({ header: '**Blocked by:** HK2\n', files: '- `src/app.mjs` lines 20-30, `handleKeyDown()` — h' }), options))
})

test('HK79 AC1: hkb pointer prints one Files line covering every occurrence', () => {
  const tasks = join(root, 'TASKS')
  mkdirSync(join(tasks, 'planning'), { recursive: true })
  writeFileSync(join(tasks, 'planning', 'T-1.md'), '# T-1 — card\n**Workflow:** card-owned\n**Workflow version:** 2\n**Workspace:** .\n## Files\n- `src/multi.mjs` lines 1-14, `x`\n')
  const run = (...args) => spawnSync(process.execPath, [resolve('hkb.mjs'), '--tasks', tasks, 'pointer', 'T-1', ...args], { encoding: 'utf8', windowsHide: true })
  const ok = run('src/multi.mjs', 'handleKeyDown()')
  assert.equal(ok.status, 0, ok.stderr)
  assert.equal(ok.stdout, '- `src/multi.mjs` lines 3-12, `handleKeyDown()`\n')
  assert.equal(run('src/multi.mjs', 'noSuchName').status, 1)
  assert.equal(run(join(root, 'src', 'multi.mjs'), 'handleKeyDown()').status, 1)
})

test('HK79 AC2: a range that misses the name lists the lines where it occurs', () => {
  const at = (path, range) => plan({ files: `- \`${path}\` lines ${range}, \`handleKeyDown()\` — h`, changes: `- \`${path}\` lines ${range}, \`handleKeyDown()\`: guard.` })
  assert.throws(() => validatePlan(at('src/multi.mjs', '5-8'), options), /occurs on lines 3, 12/)
  assert.throws(() => validatePlan(at('src/app.mjs', '20-30'), options), /occurs on lines 10\b/)
  assert.doesNotThrow(() => validatePlan(at('src/multi.mjs', '3-12'), options))
})

test('AC3: a plan whose every entry has a correct file, range and name passes', () => {
  assert.doesNotThrow(() => validatePlan(plan(), options))
})

test('AC3b: several Files failures are refused once and every one is named', () => {
  const files = '- `src/app.mjs` — no range\n- `src/missing.mjs` lines 1-5, `foo()` — gone\n- `src/app.mjs` lines 20-30, `handleKeyDown()` — wrong lines'
  assert.throws(() => validatePlan(plan({ files }), options), (err) => {
    assert.match(err.message, /found 3 problems/)
    assert.match(err.message, /has no line range/)
    assert.match(err.message, /src\/missing\.mjs does not exist/)
    assert.match(err.message, /does not occur in those lines/)
    return true
  })
  assert.doesNotThrow(() => validatePlan(plan(), options))
})

