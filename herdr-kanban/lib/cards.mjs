const realReviewerEvidence = (evidence) =>
  evidence.length > 0 && !/^(todo|tbd|n\/a|template|placeholder|\[.*\])$/i.test(evidence)

export function currentReviewDecision(text) {
  // A pending correction invalidates any verdict retained in old evidence.
  if (/^## Current feedback\r?\nReview feedback:/m.test(text)) {
    const feedbackAt = text.indexOf('## Current feedback')
    const verdictAt = text.lastIndexOf('**Review verdict:**')
    if (verdictAt < feedbackAt) return null
  }
  let inFence = false
  let afterReset = true
  let inReviewerEvidence = false
  let evidence = ''
  let latest = null

  for (const raw of text.split(/\r?\n/)) {
    const line = raw.trim()
    if (/^```/.test(line)) {
      inFence = !inFence
      continue
    }
    if (inFence || line.startsWith('>')) continue
    if (RESET_MARKER_LINE.test(line)) {
      afterReset = true
      inReviewerEvidence = false
      evidence = ''
      latest = null
      continue
    }
    if (REVIEWER_EVIDENCE_LINE.test(line)) {
      inReviewerEvidence = afterReset
      evidence = ''
      continue
    }
    const verdict = line.match(REVIEW_VERDICT_LINE)
    if (verdict && afterReset) {
      latest = { verdict: verdict[1], evidence: evidence.trim() }
      inReviewerEvidence = false
      continue
    }
    if (inReviewerEvidence && ANY_HEADING_LINE.test(line)) {
      inReviewerEvidence = false
      continue
    }
    if (inReviewerEvidence) evidence += `${raw}\n`
  }
  if (!latest || !realReviewerEvidence(latest.evidence)) return null
  return latest
}

export function hasCurrentReviewPass(text) {
  return currentReviewDecision(text)?.verdict === 'PASS'
}

export function hasBuilderPass(card) {
  try {
    const text = readFileSync(card.path, 'utf8')
    const result = ['Implementation', 'Evidence']
      .map((name) => text.match(new RegExp(`^## ${name}\\s*\\r?\\n([\\s\\S]*?)(?=^## |$(?![\\s\\S]))`, 'm'))?.[1]?.replace(/<!--[\\s\\S]*?-->/g, '') ?? '')
      .join('\n')
    return builderPassIn(builderResult(result))
  } catch { return false }
}

// Builders also write "- Stage: builder, Outcome: PASS, Files: ..." on one line and
// "Outcome: PASS: <note>"; read those the same (Injectbuddy I556 stalled on the format).
export const BUILDER_FIELDS = ['Stage', 'Outcome', 'Files', 'Check', 'Result', 'Evidence', 'Blocker']
export const builderResult = text => text.replaceAll('**', '').replace(/^[ \t]*[-*][ \t]+/gm, '')
  .replace(new RegExp(`[,;][ \\t]*(?=(?:${BUILDER_FIELDS.join('|')}):)`, 'g'), '\n')
export const builderPassIn = result => /^Stage:\s*builder\s*$/mi.test(result) && /^Outcome:\s*PASS(?:\s*$|\s*[:.;—–-]\s*\S)/mi.test(result)

export function canArchive(card) {
  return (!card.cardOwned && !card.mission) || card.reviewPassed || !!card.audit || hasOperatorCompletion(card) ||
    (card.cardOwned && !card.autoReview && hasBuilderPass(card) && hasIntegratedWorktree(card))
}

function hasIntegratedWorktree(card) {
  try {
    return JSON.parse(readFileSync(join(dirname(dirname(card.path)), '.board-worktrees.json'), 'utf8'))[card.id]?.state === 'integrated'
  } catch { return false }
}

// Explicit human waiver is separate from Review PASS and bound to exact evidence.
export function hasOperatorCompletion(card) {
  try {
    const tasksDir = dirname(dirname(card.path))
    const receipt = JSON.parse(readFileSync(join(tasksDir, '.operator-completions.json'), 'utf8'))[card.id]
    const work = JSON.parse(readFileSync(join(tasksDir, '.board-worktrees.json'), 'utf8'))[card.id]
    const hash = path => createHash('sha256').update(readFileSync(path)).digest('hex')
    return receipt?.kind === 'explicit-user-review-waiver' && !!receipt.authorization && work?.state === 'integrated' && receipt.commit === work.commit && receipt.cardHash === hash(card.path) && receipt.evidenceHash === hash(receipt.evidencePath)
  } catch { return false }
}

// Priority lives in the card's metadata line, same as everything else the board
// reads. Editing it here keeps the file the single source of truth.
export function setPriority(tasksDir, cardId, priority) {
  const n = Math.max(0, Math.min(10, Math.round(Number(priority))))
  if (!Number.isFinite(n)) throw new Error(`priority must be 0-10, got: ${priority}`)

  const card = findCard(tasksDir, cardId)
  const text = readFileSync(card.path, 'utf8')
  const next = withPriority(text, n)
  if (next !== text) writeFileSync(card.path, next)
  return { ...card, priority: n }
}

function withPriority(text, n) {
  const line = `**Priority** ${n}/10`
  if (PRIORITY.test(text)) return text.replace(PRIORITY, line)
  const heading = text.match(HEADING)
  return heading ? text.replace(heading[0], `${heading[0]}\n\n${line}`) : `${line}\n\n${text}`
}

// The header's Blocked-by line sits right under Priority (I270's format). An empty list removes it.
function withBlockers(text, ids) {
  const line = ids.length ? `**Blocked by:** ${ids.join(', ')}` : ''
  if (/^\*\*Blocked by:\*\*/m.test(text)) return text.replace(/^\*\*Blocked by:\*\*[^\r\n]*(\r?\n)?/m, (_, eol) => line && line + (eol || ''))
  if (!line) return text
  const anchor = text.match(/^\*\*Priority\*\*[^\r\n]*/m) || text.match(/^\*\*Trivial:\*\*[^\r\n]*/m) || text.match(HEADING)
  const eol = text.includes('\r\n') ? '\r\n' : '\n'
  return anchor ? text.replace(anchor[0], `${anchor[0]}${eol}${line}`) : `${line}${eol}${eol}${text}`
}

function checkPriority(priority) {
  if (!Number.isInteger(priority) || priority < 1 || priority > 10) throw new Error(`priority must be a whole number from 1 to 10, got: ${JSON.stringify(priority)}`)
}

function cardIds(ids, field) {
  if (!Array.isArray(ids) || ids.some((b) => typeof b !== 'string' || !b.trim())) throw new Error(`${field} must be an array of card IDs`)
  return [...new Set(ids.map((b) => b.trim().toUpperCase()))]
}

// New blockers must be cards in this project (any lane, archive included), not the card itself, and must not close a loop.
function checkBlockers(board, id, ids, field) {
  ids = cardIds(ids, field)
  if (ids.includes(id)) throw new Error(`${id} cannot be blocked by itself`)
  const known = new Set(Object.values(board).flat().map((c) => c.id))
  const unknown = ids.filter((b) => !known.has(b))
  if (unknown.length) throw new Error(`${field} names no card in this project: ${unknown.join(', ')}`)
  if (cycleFor({ id, blockedBy: ids }, board)) throw new Error(`Blocking ${id} on ${ids.join(', ')} would make a dependency cycle`)
  return ids
}

// A dependency cycle among live cards; an archived card has landed, so nothing waits on it.
export function cycleFor(card, board) {
  const byId = new Map()
  for (const c of Object.entries(board).filter(([key]) => key !== 'archive').flatMap(([, cards]) => cards)) {
    if (!byId.has(c.id)) byId.set(c.id, c)
    else byId.set(c.id, null)
  }
  const seen = new Set()
  const visit = (id) => {
    if (id === card.id) return true
    if (seen.has(id)) return false
    seen.add(id)
    const next = byId.get(id)
    return !!next && (next.blockedBy || []).some(visit)
  }
  return (card.blockedBy || []).some(visit)
}

// POST /api/card-update: orchestrators maintain their own cards (priority, blockers,
// dated decision notes) without hand-editing the file. The caller sets `lockBlockers`
// while a live agent holds the card.
export function updateCard(tasksDir, cardId, { priority, addBlockedBy = [], removeBlockedBy = [], note } = {}, { lockBlockers = false, now = new Date() } = {}) {
  const card = findCard(tasksDir, cardId)
  if (card.column === 'archive') throw new Error(`${card.id} is archived; archived cards cannot be updated`)
  let text = readFileSync(card.path, 'utf8')
  const changes = []
  if (priority !== undefined) {
    checkPriority(priority)
    text = withPriority(text, priority)
    changes.push(`priority ${priority}/10`)
  }
  const add = cardIds(addBlockedBy, 'addBlockedBy'), remove = cardIds(removeBlockedBy, 'removeBlockedBy')
  if (add.length || remove.length) {
    if (lockBlockers) throw new Error(`${card.id} has a live agent in ${card.column}; blocker changes are refused until it finishes (note and priority are still allowed)`)
    checkBlockers(readBoard(tasksDir), card.id, add, 'addBlockedBy')
    const next = [...new Set([...card.blockedBy, ...add])].filter((b) => !remove.includes(b))
    text = withBlockers(text, next)
    changes.push(`blocked by ${next.join(', ') || 'nothing'}`)
  }
  if (note !== undefined) {
    const heading = typeof note?.heading === 'string' ? note.heading.trim() : ''
    const body = typeof note?.text === 'string' ? note.text.trim() : ''
    // Board markers (Review feedback, Needs you, Blocked by, ...) in a note would be read as card state.
    if (!/^[A-Za-z][A-Za-z0-9 '-]{0,39}$/.test(heading) || /^(build attempt|review feedback|needs you|kicked back|spawn failed|parked|priority)$/i.test(heading)) throw new Error('note.heading must be a short plain label such as "Decision" or "Operator decision" (letters, digits, spaces; at most 40 characters)')
    if (!body) throw new Error('note.text is required')
    // Board fields are bold labels or headings at the start of a line (`**Blocked by:** ...`,
    // `**Investigation approved:** yes`, `## Files`), plus any `**Label:**`. A glob such as
    // public/legacy/** mid-line is not one (Injectbuddy chat, 2026-09-26).
    if (/^[\s>*-]*\*\*|\*\*[^*\n]+:\*\*|^\s*#/m.test(body)) throw new Error('note.text must be plain text: no line starting with ** bold, no **Label:** field and no # headings (the board reads those as card fields); ** inside a path such as public/legacy/** is fine')
    const eol = text.includes('\r\n') ? '\r\n' : '\n'
    text = `${text.trimEnd()}${eol}${eol}**${heading}** ${now.toISOString()}${eol}${eol}${body.replace(/\r?\n/g, eol)}${eol}`
    changes.push(`note: ${heading}`)
  }
  if (!changes.length) throw new Error('Nothing to update: send priority, addBlockedBy, removeBlockedBy or note')
  writeFileSync(card.path, text)
  appendHistory(tasksDir, card.id, { event: 'card-update', changes })
  return { card: parseCard(card.path, card.column), changes }
}

// Toggle the auto-review marker by rewriting the one line in the card. The card
// stays the source of truth, so the flag survives outside the board entirely.
export function setAutoReview(tasksDir, cardId, on) {
  const card = findCard(tasksDir, cardId)
  const text = readFileSync(card.path, 'utf8')
  const has = AUTOREVIEW.test(text)

  let next
  if (!on) {
    // Off means no marker, not a marker saying no. Toggling on and back off has
    // to leave the card byte-identical, or every toggle dirties someone's diff.
    next = has ? text.replace(/\n*^\*\*Auto-review:\*\*[^\n]*\n/im, '\n') : text
  } else if (has) {
    next = text.replace(AUTOREVIEW, '**Auto-review:** yes')
  } else {
    // Put it directly under the heading, where the other metadata already lives.
    const heading = text.match(HEADING)
    next = heading
      ? text.replace(heading[0], `${heading[0]}\n\n**Auto-review:** yes`)
      : `**Auto-review:** yes\n\n${text}`
  }
  if (next !== text) writeFileSync(card.path, next)
  return { ...card, autoReview: on }
}

// Archive holds most cards and rarely changes, yet every poll re-stats each file
// (most of the board server's CPU, 2026-09-27). Reuse it until a card enters or
// leaves (the folder's mtime changes), or ARCHIVE_TTL_MS passes for in-place edits.
const ARCHIVE_TTL_MS = 30000
const archiveCache = new Map()
function readColumn(tasksDir, col) {
  if (col.key !== ARCHIVE.key) return readColumnNow(tasksDir, col)
  let dirMtime
  try { dirMtime = statSync(join(tasksDir, col.dir)).mtimeMs } catch { return [] }
  const hit = archiveCache.get(tasksDir)
  if (hit && hit.dirMtime === dirMtime && Date.now() - hit.at < ARCHIVE_TTL_MS) return structuredClone(hit.cards)
  const cards = readColumnNow(tasksDir, col)
  archiveCache.set(tasksDir, { dirMtime, at: Date.now(), cards })
  return structuredClone(cards)
}

function readColumnNow(tasksDir, col) {
  const dir = join(tasksDir, col.dir)
  if (!existsSync(dir)) return []
  return readdirSync(dir)
    .filter((f) => f.toLowerCase().endsWith('.md') && !NOT_A_CARD.test(f))
    .map((f) => {
      try {
        return parseCard(join(dir, f), col.key)
      } catch {
        return null // a file mid-write; the next watch event will pick it up
      }
    })
    .filter(Boolean)
    .sort((a, b) => b.priority - a.priority || a.id.localeCompare(b.id))
}

// A parked card is one an agent has already declared unresolvable without the
// operator (`hkb park`). The auto-manager sweep skips it, so a card that needs a
// credential or a taste call is not re-read every 15 minutes forever. Clearing the
// marker is the operator's act — edit or move the card and the sweep sees it again.
export const isParked = (card) => /\*\*Parked\*\*/.test(readFileSync(card.path, 'utf8'))

// Full board snapshot: { planning: [...], planned: [...], ..., archive: [...] }
export function readBoard(tasksDir) {
  const board = {}
  for (const col of ALL) board[col.key] = readColumn(tasksDir, col)
  return board
}

// Ids come from filenames, and real repos reuse numbers over time — an archived
// T-06 and a live T-06 can genuinely coexist. Archive never wins, and a tie
// between two live cards is an error rather than a coin flip, because the caller
// is usually about to move one of them.
export function findCard(tasksDir, cardId) {
  const id = String(cardId).toUpperCase()
  const live = ALL.filter((col) => col.key !== ARCHIVE.key).flatMap((col) => readColumn(tasksDir, col)).filter((c) => c.id === id)
  const all = live.length ? live : readColumn(tasksDir, ARCHIVE).filter((c) => c.id === id)
  if (!all.length) throw new Error(`unknown card: ${cardId}`)

  if (live.length > 1) {
    if (live.length === 2 && mergeLateCopy(tasksDir, id, live)) return findCard(tasksDir, id)
    throw Object.assign(new Error(`${id} is ambiguous — ${live.map((c) => `${c.column}/${c.file}`).join(' and ')}`), { ambiguous: id })
  }
  return live[0] ?? all[0]
}

// Tradeflow T-42: a live agent wrote its result to the lane path the board had just
// moved the card out of, recreating the file there. When the last transition went
// A -> B, both copies share a file name and the A copy was written after that move,
// the A copy is that late write: its ## sections the B copy lacks are appended to B
// (a later same-named section wins in briefs), and the file is kept in .stray/.
function mergeLateCopy(tasksDir, id, copies) {
  const move = lastTransition(tasksDir, id)
  const late = copies.find((c) => c.column === move?.from), current = copies.find((c) => c.column === move?.to)
  if (!late || !current || late.file !== current.file || statSync(late.path).mtimeMs < Date.parse(move.at)) return false
  const lateText = readFileSync(late.path, 'utf8'), text = readFileSync(current.path, 'utf8')
  // Current feedback is the board's own note; the late copy's is the one it replaced.
  const added = lateText.split(/(?=^## )/m).map((s) => s.trim()).filter((s) => s.startsWith('## ') && !s.startsWith('## Current feedback') && !text.includes(s))
  appendHistory(tasksDir, id, { event: 'late-copy-merged', from: late.column, text: lateText })
  if (added.length) writeFileSync(current.path, `${text.trimEnd()}\n\n${added.join('\n\n')}\n`)
  mkdirSync(join(tasksDir, '.stray'), { recursive: true })
  renameSync(late.path, join(tasksDir, '.stray', `${Date.now()}-${late.column}-${late.file}`))
  return true
}

// Move a card between columns. This IS the state change — there is nothing else to update.
export function moveCard(tasksDir, cardId, toKey, options = {}) {
  // Issues is retired (operator 2026-09-25): anything aimed at it goes to Planning.
  if (toKey === 'issues') toKey = 'planning'
  let col = columnByKey(toKey)
  if (!col) throw new Error(`unknown column: ${toKey}`)

  const card = options.sourcePath
    ? Object.values(readBoard(tasksDir)).flat().find(c => c.path === options.sourcePath)
    : findCard(tasksDir, cardId)
  if (!card) throw new Error(`unknown card source: ${options.sourcePath}`)
  if (card.column === toKey) return card
  // Completed means "built, ready to integrate". Review runs after integration,
  // so Auto-review cards need only the Builder PASS here.
  if (toKey === 'completed' && card.cardOwned && !card.trivial && !card.reviewPassed && !hasBuilderPass(card)) {
    throw new Error(`${card.id} requires Builder PASS before Completed`)
  }
  if (card.cardOwned && ['planned', 'queue'].includes(toKey)) validatePlan(readFileSync(card.path, 'utf8'), { requireReadiness: !!options.plannerAssignment, workspace: options.planWorkspace, sharedFiles: options.sharedFiles })
  if (card.column === 'archive' && toKey !== 'archive') {
    // Only reachable when every copy of the id is archived; moving one back out
    // silently is more surprising than refusing.
    throw new Error(`${card.id} only exists in archive (${card.file}) — move it by hand if you meant that`)
  }
  if (toKey === 'archive' && !options.operatorArchive && !canArchive(card)) {
    throw new Error(`${card.id} is a mission card and needs Reviewer evidence plus Review verdict: PASS before archive`)
  }

  const text = readFileSync(card.path, 'utf8')
  if (toKey === 'archive' && card.audit) {
    const error = auditArchiveError(text, id => id !== card.id && !!findCard(tasksDir, id))
    if (error) throw new Error(error)
  }
  const transition = recoveryTransition(text, card.column, toKey, options)
  toKey = transition.to
  col = columnByKey(toKey)
  const dest = join(tasksDir, col.dir)
  mkdirSync(dest, { recursive: true })
  let target = join(dest, card.file)
  if (options.sourcePath && existsSync(target)) {
    const ext = extname(card.file)
    const stem = card.file.slice(0, -ext.length)
    let copy = 2
    do { target = join(dest, `${stem}-duplicate-${copy++}${ext}`) } while (existsSync(target))
  }
  if (existsSync(target)) throw new Error(`already exists in ${toKey}: ${card.file}`)

  appendHistory(tasksDir, card.id, { event: 'transition', from: card.column, to: toKey, text, ...(options.operatorArchive && toKey === 'archive' ? { note: 'Archived by operator from board without independent review' } : {}) })
  if (transition.text !== text) writeFileSync(card.path, transition.text)
  renameSync(card.path, target)
  return { ...card, column: toKey, path: target }
}

function constraintsFor(tasksDir, category) {
  if (!existsSync(join(tasksDir, 'PROJECT-CONSTRAINTS.md'))) return '<!-- Optional; populated only when this project has relevant constraints. -->'
  return projectConstraints(tasksDir, category) || '<!-- No project-specific constraints for this category. -->'
}

// Legacy cards (migrated from TASKS.md, not card-owned) have no Planner path, so they
// sat in Planning until the stall watchdog sent them to Owner (Healthypets T-01..03).
// Convert in place to the card-owned template: same file, ID and title; the authored
// body (before the first --- board-event separator, headings demoted) becomes the
// Approved brief. The full original text is saved to card history first.
export function convertLegacyCard(tasksDir, card, now = new Date()) {
  const original = readFileSync(card.path, 'utf8')
  if (card.audit || /^\*\*Workflow:\*\* card-owned$/m.test(original)) return card
  const entry = appendHistory(tasksDir, card.id, { event: 'legacy-conversion-source', sourcePath: card.path, sourceHash: createHash('sha256').update(original).digest('hex'), text: original })
  const lines = original.split(/\r?\n/)
  const body = lines.slice(lines.findIndex(line => HEADING.test(line)) + 1).join('\n')
    .split(/^---[ \t]*$/m)[0].replace(/^#{1,2}(?= )/gm, '###').trim()
  const brief = `${body}\n\nConverted from a legacy card on ${now.toISOString()}; the original text, including its board history, is saved in ${historyPath(tasksDir, card.id).replaceAll('\\', '/')} (entry ${entry.id}).`
  const values = { ID: card.id, TITLE: card.title, CREATED: original.match(/^\*\*Created:\*\*\s*(\S+)/m)?.[1] || now.toISOString(), CATEGORY: card.category, WORKSPACE: card.workspace || '.', MISSION: '', BRIEF: brief, PROJECT_CONSTRAINTS: constraintsFor(tasksDir, card.category) }
  const text = readFileSync(TEMPLATE, 'utf8')
    .replace(/\{\{(ID|TITLE|CREATED|CATEGORY|WORKSPACE|MISSION|BRIEF|PROJECT_CONSTRAINTS)\}\}/g, (_, key) => values[key])
    .replace(/^\*\*Priority\*\* \d+\/10$/m, `**Priority** ${card.priority || 5}/10${card.blockedBy?.length ? `\n**Blocked by:** ${card.blockedBy.join(', ')}` : ''}`)
  const temp = `${card.path}.convert-${process.pid}.tmp`
  writeFileSync(temp, text, { flag: 'wx' })
  renameSync(temp, card.path)
  return parseCard(card.path, card.column)
}

// Blocked-by prerequisites not yet landed: Completed and integrated, or Archive.
export function unmetBlockers(card, board, integrated = {}) {
  const live = Object.entries(board).filter(([key]) => key !== 'archive').flatMap(([, cards]) => cards)
  return (card.blockedBy || []).filter((id) => {
    const alive = live.filter((c) => c.id === id)
    const archived = board.archive.filter((c) => c.id === id)
    if (!alive.length && archived.length === 1) return false
    // Review now happens after integration, so an integrated card in Review has already landed.
    return !(alive.length === 1 && archived.length === 0 && ['completed', 'review'].includes(alive[0].column) && integrated[id]?.state === 'integrated')
  })
}
// Unmet prerequisites that are still live cards: an allowed wait (TF44). A
// prerequisite missing from the board can never land, so that is not a wait.
export function waitingOnPrerequisites(card, board, integrated = {}) {
  const unmet = unmetBlockers(card, board, integrated)
  const live = new Set(Object.entries(board).filter(([key]) => key !== 'archive').flatMap(([, cards]) => cards.map((c) => c.id)))
  return unmet.length && unmet.every((id) => live.has(id)) ? unmet : []
}

// `prefix` is the project's card prefix (board.config.json cardPrefixes); without
// one the project keeps issuing legacy T- ids.
export function createCard(tasksDir, { title, brief, category = 'code', workspace = '.', audit = '', tools = '', mission = '', prefix = 'T-', priority, blockedBy, now = new Date() }) {
  if (typeof title !== 'string' || !title.trim() || title.length > 200 || /[\r\n]/.test(title)) throw new Error('A single-line title of at most 200 characters is required')
  if (typeof brief !== 'string' || !brief.trim() || brief.length > 50000) throw new Error('An approved brief of at most 50000 characters is required')
  if (typeof mission !== 'string' || /[\r\n]/.test(mission)) throw new Error('Invalid mission')
  category = String(category).toLowerCase()
  if (!CATEGORIES.includes(category)) throw new Error(`Category must be one of: ${CATEGORIES.join(', ')}`)
  workspace = String(workspace).replace(/\\/g, '/').trim() || '.'
  if (/^[A-Za-z]:|^\/|(^|\/)\.\.(\/|$)/.test(workspace)) throw new Error('Workspace must be a project-relative path')
  audit = String(audit).toLowerCase()
  if (audit && !AUDITS.includes(audit)) throw new Error(`Audit must be one of: ${AUDITS.join(', ')}`)
  if (audit === 'general' && !String(tools ?? '').trim()) tools = '- chrome-devtools (headless isolated browser: screenshots, DOM measurements, console and network)'
  if (audit && (typeof tools !== 'string' || !tools.trim())) throw new Error('Audit cards require exact tools/MCPs')
  if (priority !== undefined) checkPriority(priority)
  const board = readBoard(tasksDir)
  const id = nextCardId(prefix, Object.values(board).flat().map(c => c.id))
  if (blockedBy !== undefined) blockedBy = checkBlockers(board, id, blockedBy, 'blockedBy')
  const dir = join(tasksDir, audit ? 'review' : 'planning')
  mkdirSync(dir, { recursive: true })
  const path = join(dir, audit ? `${id}-audit-${audit}.md` : `${id}-approved-job.md`)
  const template = readFileSync(audit ? AUDIT_TEMPLATES[audit] : TEMPLATE, 'utf8')
  // The project copy is a reference; creation always uses the board's canonical template.
  if (!audit) writeFileSync(join(tasksDir, 'TASK-TEMPLATE.md'), template)
  const values = { ID: id, TITLE: title.trim(), CREATED: now.toISOString(), CATEGORY: category, WORKSPACE: workspace, AUDIT: audit, TOOLS: tools.trim(), MISSION: mission ? `**Mission:** ${mission}` : '', BRIEF: brief.trim(), PROJECT_CONSTRAINTS: constraintsFor(tasksDir, category) }
  let text = template.replace(/\{\{(ID|TITLE|CREATED|CATEGORY|WORKSPACE|AUDIT|TOOLS|MISSION|BRIEF|PROJECT_CONSTRAINTS)\}\}/g, (_, key) => values[key])
  if (priority !== undefined) text = withPriority(text, priority)
  if (blockedBy?.length) text = withBlockers(text, blockedBy)
  writeFileSync(path, text, { flag: 'wx' })
  return parseCard(path, audit ? 'review' : 'planning')
}

// Whether an agent for this card needs the browser MCPs (chrome-devtools, playwright,
// computer-use). UI cards and any card naming browser work get them; others start lean.
export function needsBrowser(card) {
  if (card.category === 'ui' || card.audit) return true
  try { return /chrome-devtools|playwright|browser|screenshot|viewport|lighthouse|visual|\b\d{3,4}\s?px\b/i.test(readFileSync(card.path, 'utf8')) } catch { return true }
}
