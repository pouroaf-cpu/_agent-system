// `workspace` (absolute) is passed only at a Planner handoff, so cards already
// queued or working are never blocked retroactively by the plan check.
export function validatePlan(text, { requireReadiness = false, workspace: planRoot = null, sharedFiles = [] } = {}) {
  const section = (name) => (text.match(new RegExp(`^## ${name}\\s*\\r?\\n([\\s\\S]*?)(?=^## |$(?![\\s\\S]))`, 'm'))?.[1] ?? '').replace(/<!--[\s\S]*?-->/g, '').replace(/^\*\*Callers checked:\*\*\s*$/gm, '').trim()
  const workspace = text.match(/^\*\*Workspace:\*\*\s*([^\n]+)$/im)?.[1]?.trim() || '.'
  const readinessLine = text.match(/^\*\*Plan readiness:\*\*[^\n]*$/im)?.[0]
  const readiness = text.match(/^\*\*Plan readiness:\*\*\s*(build-ready|investigation)\s*$/im)?.[1]?.toLowerCase()
  if (requireReadiness && !readinessLine) throw new Error('Plan incomplete: authenticated Planner handoff requires **Plan readiness:** build-ready or investigation')
  if (readinessLine && !readiness) throw new Error('Plan incomplete: Plan readiness must be build-ready or investigation')
  if (/^[A-Za-z]:|^\/|(^|\/)\.\.(\/|$)/.test(workspace.replace(/\\/g, '/'))) {
    throw new Error('Plan incomplete: Workspace must be a project-relative path')
  }
  for (const name of ['Approved brief', 'Files', 'Implementation plan', 'Acceptance criteria']) {
    if (!section(name)) throw new Error(`Plan incomplete: fill ## ${name} before handoff; keep the template headings`)
  }
  if (/^\*\*Workflow version:\*\* 2$/m.test(text)) {
    const criteria = [...section('Acceptance criteria').matchAll(/^-\s+(AC\d+):\s+\S.+$/gm)].map(m => m[1])
    const checks = section('Outcome checks')
    // A cell may hold an escaped pipe, \|, as Markdown allows (Tradeflow TF121).
    const cell = String.raw`(?:\\.|[^|\\])+`
    const unmapped = criteria.find(id => !new RegExp(String.raw`^\s*\|?\s*${id}\s*\|${cell}\|${cell}\|${cell}\|?\s*$`, 'm').test(checks))
    if (!criteria.length || new Set(criteria).size !== criteria.length || unmapped) throw new Error(`Plan incomplete: map each AC ID to change, acceptance check and negative check under Outcome checks${unmapped ? ` (no 4-column row for ${unmapped})` : ''}`)
    if (!section('Prerequisites')) throw new Error('Plan incomplete: state workspace prerequisites (or explicitly none)')
  }
  const fileLines = [...section('Files').matchAll(/^-\s+`([^`]+)`([^\n]*)/gm)]
  const files = fileLines.map(m => m[1])
  // A glob is allowed only for files generated by a script this card also lists (Injectbuddy I302).
  const generator = (rest) => rest.match(/generated by\s+`?([^`\s]+)`?/i)?.[1]
  const unmarked = fileLines.find(([, p, rest]) => isGlob(p) && !generator(rest))
  // I528: the generic message below read as "no globs at all", so a Planner with a valid generated set gave up.
  if (unmarked) throw new Error(`Plan incomplete: ## Files glob ${unmarked[1]} needs the exact words generated by \`<script>\` on its line (e.g. - \`public/legacy/*/index.html\` — generated by \`scripts/x.mjs\`), with that script listed as its own bullet. Other globs are refused.`)
  // I530: name the path that failed; the old message blamed globs for a .py bullet.
  const bad = fileLines.find(([, p]) => /[\\:?<>]|(^|\/)\.\.(\/|$)|^\//.test(p) || !/\.(tsx?|jsx?|mjs|cjs|css|json|md|html?|txt|xml|svg|ya?ml|sql|py|sh|ps1)$/.test(p) && !(readiness === 'investigation' && p.endsWith('/')))
  if (!files.length || bad) {
    throw new Error(`Plan incomplete: ## Files needs exact relative file paths as - \`path/to/file.css\` bullets${bad ? `; ${bad[1]} is not one (no placeholders, folders, absolute or ../ paths, or unknown file types)` : ''}`)
  }
  for (const [, p, rest] of fileLines) {
    const script = isGlob(p) && generator(rest)
    if (script && !files.some(f => !isGlob(f) && f.replace(/^\.\//, '') === script.replace(/^\.\//, ''))) throw new Error(`Plan incomplete: ## Files glob ${p} is generated by ${script}, but ${script} is not listed in ## Files. List the script as its own bullet.`)
  }
  if (/^\*\*Trivial:\*\*\s*yes\s*$/im.test(text) && files.length > 2) {
    throw new Error('Trivial cards may list no more than two files')
  }
  // A card that edits many files is several cards: Injectbuddy I191 (33 files) spent 14.5M
  // tokens across Planner loops and locked files the whole queue waited on (operator, 2026-09-26).
  const editedFiles = section('Files').split(/\r?\n/).filter(line => /^-\s+`[^`]+`/.test(line) && !REFERENCE_ONLY.test(line)).map(line => line.match(/`([^`]+)`/)[1])
  const edited = editedFiles.length
  if (planRoot && edited > MAX_PLAN_FILES) throw new Error(`Plan too wide: ${edited} files to edit (limit ${MAX_PLAN_FILES}). Don't hand this off as one card. If the files are generated by one script, list the script plus one glob line marked 'generated by <script>' (- \`path/*/file.html\` — generated by \`scripts/x.mjs\`), which counts as one file. Otherwise split it: hkb split <card-id> "1. <smaller card: its outcome and files> 2. ..." so the project's orchestrator re-cards each part.`)
  if (readiness === 'investigation') {
    const plan = section('Implementation plan').replaceAll('**', '')
    if (!/(?:check|measurement)\s*(?:commands?|method)?\s*:\s*\S|setup\/start\/check commands?[^\n]*\n[\s\S]*?```/i.test(plan) || !/(?:expected result|disposition)\s*:\s*\S/i.test(plan) || !/stop rules?\s*:\s*\S/i.test(plan)) {
      throw new Error('Plan incomplete: investigation needs a measurement/check, expected result or disposition, and stop rules')
    }
    // Checked last: only the operator can add this marker, so a plan failing on it
    // alone is waiting for the operator, not for more planning (T-148).
    if (!/^\*\*Investigation approved:\*\* yes\s*$/im.test(text.split(/^## Approved brief/m)[0])) throw Object.assign(new Error('Plan incomplete: investigation requires explicit approval on the card'), { operatorApproval: true })
  }
  if (readiness === 'build-ready') {
    const plan = section('Implementation plan')
    const required = [
      ['agreed outcome', /(?:^|\n)[ \t]*(?:[-*][ \t]*)?(?:outcome|agreed outcome)[ \t]*:[ \t]*[^\r\n]+/im],
      ['unchanged constraints', /(?:^|\n)[ \t]*(?:[-*][ \t]*)?unchanged constraints?[ \t]*:[ \t]*[^\r\n]+/im],
      ['observed cause and evidence', /(?:^|\n)[ \t]*(?:[-*][ \t]*)?(?:observed cause|cause)[ \t]*:[ \t]*[^\r\n]+[\s\S]*?(?:^|\n)[ \t]*evidence[ \t]*:[ \t]*[^\r\n]+/im],
      ['inspected current revision/state', /(?:^|\n)[ \t]*(?:[-*][ \t]*)?inspected current (?:revision\/state|revision|state)[ \t]*:[ \t]*[^\r\n]+/im],
      ['concrete changes', /(?:^|\n)[ \t]*(?:[-*][ \t]*)?(?:change|changes|concrete changes)[ \t]*:[ \t]*[^\r\n]+/im],
      ['runnable check and expected result', /(?:^|\n)[ \t]*(?:[-*][ \t]*)?(?:check|check command|setup)[ \t]*:[ \t]*[^\r\n]+[\s\S]*?(?:^|\n)[ \t]*(?:expected(?: result)?|result)[ \t]*:[ \t]*[^\r\n]+/im],
      ['scope/stop rules', /(?:^|\n)[ \t]*(?:[-*][ \t]*)?(?:scope|stop rules?)[ \t]*:[ \t]*[^\r\n]+/im],
    ]
    const missing = required.filter(([, pattern]) => !pattern.test(plan)).map(([name]) => name)
    // Say the exact form: a Claude Haiku Planner wrote "### Observed cause" headings and retried
    // the same shape ten times before escalating (Injectbuddy I260, 2026-09-26).
    if (missing.length) throw new Error(`Plan incomplete: build-ready plan needs ${missing.join(', ')}. Inside ## Implementation plan, write each as a line that starts with its label and a colon (headings do not count): "Agreed outcome: ...", "Unchanged constraints: ...", "Cause: ..." then "Evidence: ...", "Inspected current state: ...", "Changes: ...", "Check: ..." then "Expected result: ...", "Scope: ...".`)
    const cause = plan.match(/(?:^|\n)\s*(?:[-*]\s*)?(?:observed cause|cause)\s*:\s*([^\n]+)/i)?.[1] || ''
    if (/\b(?:unknown|unclear|tbd|todo|investigate)\b/i.test(cause)) throw new Error('Plan incomplete: unknown cause is investigation, not build-ready')
    if ([...section('Files').matchAll(/^[-*]\s+`[^`]+`\s*$/gm)].length) throw new Error('Plan incomplete: each build-ready file needs a concrete target/purpose')
  }
  if (planRoot) {
    // Card checkouts share the integration node_modules through a junction, so an install
    // there rewrote the shared copy under running Builders (throughput audit 2026-09-26 F3).
    const steps = `${section('Prerequisites')}\n${section('Implementation plan')}`.split(/\r?\n/).filter(line => !/\b(?:do not|don't|never|no|avoid|without)\b/i.test(line)).join('\n')
    const install = steps.match(/\b(?:npm (?:ci|install|i)|pnpm (?:install|i)|yarn install)\b/i)?.[0]
    if (install && !editedFiles.some(f => /(^|\/)(package\.json|package-lock\.json|npm-shrinkwrap\.json|pnpm-lock\.yaml)$/.test(f))) throw new Error(`Plan check failed: the plan runs \`${install}\`, but card checkouts share the integration node_modules through a junction, and installing there rewrites it under running Builders. Remove the install step (dependencies are already installed), or list package.json or the lockfile in ## Files if this card changes dependencies.`)
    // Shared per-project check scripts (projectSettings.<project>.sharedFiles) were locked by
    // every card that added its own check to them, one card at a time (Injectbuddy
    // scripts/capture-authed.mjs, 15 cards; throughput audit F1).
    const slashed = p => p.replaceAll('\\', '/').replace(/^\.\//, '').toLowerCase()
    const same = (a, b) => a === b || a.endsWith(`/${b}`) || b.endsWith(`/${a}`)
    const about = `${text.match(/^# .*$/m)?.[0] || ''}\n${section('Approved brief')}`.replaceAll('\\', '/').toLowerCase()
    const shared = editedFiles.find(f => sharedFiles.some(s => same(slashed(f), slashed(s))) && !about.includes(slashed(f)) && !about.includes(basename(f).toLowerCase()))
    if (shared) {
      const id = text.match(/^# (\S+)/m)?.[1]?.toLowerCase() || '<card-id>'
      throw new Error(`Plan check failed: ${shared} is shared by every card in this project, and locking it makes the other cards wait. Leave it out of ## Files and write this card's own check as scripts/check-${id}-*.mjs (new), importing what it needs from ${shared}. Only a card whose title or Approved brief names ${shared} may change it.`)
    }
    checkPlanPaths(planRoot, section('Files'), section('Prerequisites'), section('Implementation plan'))
    if (readiness === 'build-ready' && !/^\*\*Callers checked:\*\*[ \t]*\S/m.test(section('Implementation plan'))) throw new Error('Plan check failed: ## Implementation plan needs a **Callers checked:** line listing every file that references each changed function/export (or "none"). Grep for each changed symbol first.')
    // Most Builder kick-backs were plans whose own check did not match the code: a wrong
    // selector (I427), a screenshot count the script never produced (I432), a zero-reference
    // AC that files outside ## Files made impossible (I445). Running the check once first catches them.
    if (readiness === 'build-ready' && !/^\*\*Base check:\*\*[ 	]*\S/m.test(section('Implementation plan'))) throw new Error('Plan check failed: ## Implementation plan needs a **Base check:** line: run the Check once on the current integration checkout and record the command and what it printed (a regression check should fail there; a count, selector or file it relies on must exist). If it cannot run before the change (it tests a file this card creates), say why.')
  }
}

// A card worktree is a checkout of the integration HEAD, so a plan may only rely on
// files git tracks there (T-145/T-148, Kiwitown T-1). Untracked or gitignored files
// (TASKS/, *.md in some projects) exist for the Planner but not for the Builder.
// Checks ## Files and backticked path-shaped words in ## Prerequisites and
// ## Implementation plan, never prose.
function checkPlanPaths(planRoot, filesSection, prereqSection, planSection) {
  const root = planRoot.replaceAll('\\', '/')
  const readOnly = 'cite a file that exists only outside git by absolute path as a read-only reference in ## Prerequisites'
  const tracked = (path) => {
    const git = spawnSync('git', ['-C', planRoot, 'cat-file', '-e', `HEAD:./${path.replace(/\/+$/, '')}`], { windowsHide: true, encoding: 'utf8' })
    if (git.status === 0) return true
    if (git.status === null || /not a git repository/i.test(git.stderr)) return existsSync(resolve(planRoot, path)) // non-Git workspace
    return false
  }
  const problem = (path) => tracked(path) ? null
    : existsSync(resolve(planRoot, path)) ? `exists in ${root} but is not tracked by git at HEAD (untracked or gitignored), so the card worktree will not have it`
      : `does not exist in ${root}`
  const newFiles = new Set()
  for (const [, path, rest] of filesSection.matchAll(/^[-*]\s+`([^`]+)`([^\n]*)/gm)) {
    if (/\(new\b[^)]*\)/i.test(rest)) { newFiles.add(path); continue }
    if (isGlob(path)) {
      const git = spawnSync('git', ['-C', planRoot, 'ls-files', '--', `:(glob,icase)${path}`], { windowsHide: true, encoding: 'utf8' })
      if (git.status === 0 && !git.stdout.trim()) throw new Error(`Plan check failed: ## Files glob ${path} matches no file tracked by git in ${root}. Fix the glob so it matches the generated files.`)
      continue // non-Git workspace: nothing to check against
    }
    const why = problem(path)
    if (why) throw new Error(`Plan check failed: ## Files path ${path} ${why}. Fix the path, mark a file this card creates with (new), or ${readOnly}.`)
  }
  // Ignored root files such as .env.devtools.local exist only in the integration
  // checkout (Injectbuddy I227/I265); the Builder gets the project's envFile instead.
  const hint = (path) => /(^|\/)\.env/i.test(path)
    ? 'Card checkouts have no ignored .env files: rely on the project\'s approved envFile (board.config.json projectSettings envFile), which the Builder runs with node --env-file="<absolute envFile>"; never copy or test it inside the card checkout'
    : `Mark a file this card creates with (new), or ${readOnly}`
  for (const [name, text] of [['Prerequisites', prereqSection], ['Implementation plan', planSection]]) {
    for (const [, span, rest] of text.matchAll(/`([^`]+)`([^\n`]*)/g)) {
      if (/^\s*\(new\b/i.test(rest)) continue
      const single = !/\s/.test(span.trim())
      for (const word of span.trim().split(/\s+/)) {
        const token = word.split('=').pop().replace(/^["'(]+|["'),;]+$/g, '').replaceAll('\\', '/').replace(/^\.\//, '')
        if (/^[A-Za-z]:\//.test(token)) {
          if (single && name === 'Prerequisites' && !existsSync(token)) throw new Error(`Plan check failed: ## Prerequisites path ${token} does not exist. Remove it or cite a file that exists.`)
          continue
        }
        // Relative file paths only (a/b.ext, .env.local), not URLs, globs or node_modules (junctioned in).
        if (!/^[\w@.[\]-]+(?:\/[\w@.[\]-]+)*\.[\w-]{1,20}$/.test(token) || /^node_modules\//.test(token) || /(^|\/)\.\.(\/|$)/.test(token) || newFiles.has(token)) continue
        // A lone a/b.ext prerequisite must exist and be tracked. Anything else (root-level
        // names, command arguments, plan steps) is refused only when it is a file the
        // Planner can see that the card worktree will not have.
        const why = single && name === 'Prerequisites' && token.includes('/') ? problem(token)
          : statSync(resolve(planRoot, token), { throwIfNoEntry: false })?.isFile() ? problem(token) : null
        if (why) throw new Error(`Plan check failed: ## ${name} path ${token} ${why}. ${hint(token)}.`)
      }
    }
  }
}

// A complete plan held only by an operator-only marker. The board asks the operator
// once (Owner) instead of re-prompting a Planner that cannot add the marker.
export function awaitsOperatorApproval(text) {
  try { validatePlan(text) } catch (error) { return !!error.operatorApproval }
  return false
}
